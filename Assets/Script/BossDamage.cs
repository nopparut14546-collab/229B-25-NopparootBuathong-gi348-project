using UnityEngine;

public class BossDamage : MonoBehaviour
{
    public int damage = 50;
    public float knockbackPower = 100f;
    public float upForce = 20f;

    private void OnCollisionEnter(Collision collision)
    {
        if (collision.gameObject.CompareTag("Player"))
        {
            // ?????
            PlayerHealth hp = collision.gameObject.GetComponent<PlayerHealth>();
            if (hp != null) hp.TakeDamage(damage);

            // ???? Knockback ???????
            Rigidbody playerRb = collision.gameObject.GetComponent<Rigidbody>();
            if (playerRb != null)
            {
                // ???????????
                Vector3 pushDir = (collision.transform.position - transform.position);
                pushDir.y = 0;
                pushDir = pushDir.normalized;

                // [?????????? .velocity = Vector3.zero] 
                // ????????????????????? VelocityChange ???
                // ???????????????????????????????????????????????????? (Mass) ??????????????? outdated
                playerRb.AddForce(-playerRb.velocity, ForceMode.VelocityChange);

                // ?????? Super Knockback ??????
                Vector3 finalForce = (pushDir * knockbackPower) + (Vector3.up * upForce);
                playerRb.AddForce(finalForce, ForceMode.Impulse);
            }
        }
    }
}